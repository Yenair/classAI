import 'dart:convert';
import 'dart:math';
import 'dart:typed_data';
import 'package:crypto/crypto.dart';
import 'package:cryptography/cryptography.dart';

class ArgonParams {
  final int memory;     // KB
  final int iterations;
  final int parallelism;
  final int saltLength;

  const ArgonParams({
    required this.memory,
    required this.iterations,
    required this.parallelism,
    this.saltLength = 32,
  });

  static Future<ArgonParams> forDevice() async {
    // Safe defaults – works on all Android/iOS devices
    return const ArgonParams(
      memory: 32768,
      iterations: 3,
      parallelism: 2,
      saltLength: 32,
    );
  }
}

class EncryptionUtils {
  /// Derive a 256-bit key from password using Argon2id
  static Future<Uint8List> deriveKey(
    String password,
    Uint8List salt,
    ArgonParams params,
  ) async {
    final argon2 = Argon2id(
      parallelism: params.parallelism,
      memory: params.memory,
      iterations: params.iterations,
      hashLength: 32,
    );
    final key = await argon2.deriveKey(
      secretKey: SecretKey(utf8.encode(password)),
      nonce: salt,
    );
    return Uint8List.fromList(await key.extractBytes());
  }

  /// Encrypts a plaintext string using AES-256-GCM.
  static Future<String> encryptAesGcm(Uint8List key, String plaintext) async {
    final algorithm = AesGcm.with256bits();
    final secretKey = SecretKey(key);
    // The nonce is automatically generated by the algorithm if not provided.
    // This matches the approach in the official example.
    final secretBox = await algorithm.encrypt(
      utf8.encode(plaintext),
      secretKey: secretKey,
    );

    // Combine nonce + ciphertext + MAC for storage
    final combined = Uint8List.fromList([
      ...secretBox.nonce,
      ...secretBox.cipherText,
      ...secretBox.mac.bytes,
    ]);
    return base64Encode(combined);
  }

  /// Decrypts an AES-256-GCM ciphertext.
  static Future<String> decryptAesGcm(Uint8List key, String encodedCiphertext) async {
    final combined = base64Decode(encodedCiphertext);
    final algorithm = AesGcm.with256bits();
    final secretKey = SecretKey(key);

    // Extract the components from the stored combined data
    final nonceLength = algorithm.nonceLength;
    final macLength = algorithm.macAlgorithm.macLength;

    final nonce = combined.sublist(0, nonceLength);
    final ciphertext = combined.sublist(
        nonceLength, combined.length - macLength);
    final macBytes = combined.sublist(combined.length - macLength);
    final mac = Mac(macBytes);

    final secretBox = SecretBox(
      ciphertext,
      nonce: nonce,
      mac: mac,
    );

    final plaintextBytes = await algorithm.decrypt(
      secretBox,
      secretKey: secretKey,
    );
    return utf8.decode(plaintextBytes);
  }
  
  /// Wrap (encrypt) a key using AES-GCM (replaces KWP)
  static Future<String> wrapKeyAesGcm(Uint8List kek, Uint8List keyToWrap) async {
    final plaintext = base64Encode(keyToWrap);
    return await encryptAesGcm(kek, plaintext);
  }

  /// Unwrap (decrypt) a key using AES-GCM
  static Future<Uint8List> unwrapKeyAesGcm(Uint8List kek, String wrappedKey) async {
    final plaintext = await decryptAesGcm(kek, wrappedKey);
    return base64Decode(plaintext);
  }

  /// Constant‑time comparison
  static bool constantTimeCompare(String a, String b) {
    final aBytes = utf8.encode(a);
    final bBytes = utf8.encode(b);
    final maxLen = aBytes.length > bBytes.length ? aBytes.length : bBytes.length;
    int result = aBytes.length ^ bBytes.length;
    for (int i = 0; i < maxLen; i++) {
      final aByte = i < aBytes.length ? aBytes[i] : 0;
      final bByte = i < bBytes.length ? bBytes[i] : 0;
      result |= aByte ^ bByte;
    }
    return result == 0;
  }

  /// SHA-256 of a string
  static String sha256Hash(String input) {
    final bytes = utf8.encode(input);
    return sha256.convert(bytes).toString();
  }

  /// SHA-256 of bytes
  static String sha256HashBytes(Uint8List input) {
    return sha256.convert(input).toString();
  }

  /// Generate a random 256‑bit key
  static Uint8List generateKey() {
    final random = Random.secure();
    return Uint8List.fromList(List.generate(32, (_) => random.nextInt(256)));
  }
}