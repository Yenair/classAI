-- Migration: Add UNIQUE constraint on lessons.server_id and exams.server_id
-- Date: 2026-07-26 23:45:00 UTC
-- Description:
--   Stops duplicate rows from being created when the client pushes an INSERT
--   for a record that already exists on the server (stale queue entry from a
--   crash between _updateLocalServerId and removeQueueEntry).
--
--   Two-layer defence against this specific bug:
--     1. Client-side stale-INSERT detection (_pushChanges() in sync_service.dart)
--        checks if the local record already has a serverId before sending an
--        INSERT. If it does, it injects server_id into the payload and converts
--        the operation to UPDATE.
--     2. Server-side: sync-push Edge Function uses upsert().onConflict('server_id')
--        when the payload includes server_id.
--
--   The UNIQUE partial index on (server_id) WHERE server_id IS NOT NULL is NOT a
--   third defence layer for this bug. It does not fire because the stale INSERT
--   payload has no server_id (it was created before the record had one), so the
--   server generates a fresh UUID for id and server_id stays NULL — and the
--   partial index only applies to non-null values.
--
--   The UNIQUE index IS valuable as general data integrity: it prevents manual
--   INSERTs or future code bugs that explicitly reuse a non-null server_id.
--
--   Pre-migration dedup: for each server_id that appears multiple times, keeps
--   only the row with the earliest created_at (oldest creation time) and deletes
--   the rest. Rows with NULL server_id are untouched — they represent brand-new
--   records that haven't been synced yet.
--
--   SAFETY: Full table snapshots are taken BEFORE any destructive operations so
--   you can restore any row if the dedup logic turns out wrong:
--     SELECT * FROM lessons_backup_20260727;       -- pre-dedup lessons
--     SELECT * FROM exams_backup_20260727;          -- pre-dedup exams
--
--   To restore a single deleted row:
--     INSERT INTO lessons SELECT * FROM lessons_backup_20260727 WHERE id = <uuid>;
-- ============================================================================

-- ── 0. Snapshot tables before any destructive operations ─────────────────────
CREATE TABLE lessons_backup_20260727 AS SELECT * FROM lessons;
CREATE TABLE exams_backup_20260727 AS SELECT * FROM exams;

-- ── 1. Deduplicate lessons ──────────────────────────────────────────────────
-- Remove duplicates where the same server_id appears multiple times.
-- Uses DISTINCT ON to pick the oldest row (earliest created_at) per server_id.
-- All other rows with that server_id are deleted.
--
-- Why created_at instead of MIN(id)?
--   The server PK (id) is a UUID generated by gen_random_uuid(), not a
--   monotonically increasing integer — you cannot rely on MIN(id) to identify
--   the oldest row. created_at (TIMESTAMPTZ, NOT NULL) is the authoritative
--   creation timestamp and is guaranteed to be populated for all rows.
--
-- Example:
--   lessons BEFORE:
--     id=uuid-A, server_id='abc', created_at='2026-07-01 10:00:00+00'
--     id=uuid-B, server_id='abc', created_at='2026-07-01 10:00:05+00'  (stale INSERT from crash)
--     id=uuid-C, server_id='abc', created_at='2026-07-01 10:00:03+00'  (another stale INSERT)
--
--   DISTINCT ON (server_id) ORDER BY server_id, created_at ASC → picks uuid-A
--   Deletes uuid-B and uuid-C
DELETE FROM lessons
WHERE id NOT IN (
  SELECT id FROM (
    SELECT DISTINCT ON (server_id) id
    FROM lessons
    WHERE server_id IS NOT NULL
    ORDER BY server_id, created_at ASC
  ) AS keep
)
AND server_id IS NOT NULL;

-- ── 2. Deduplicate exams ────────────────────────────────────────────────────
DELETE FROM exams
WHERE id NOT IN (
  SELECT id FROM (
    SELECT DISTINCT ON (server_id) id
    FROM exams
    WHERE server_id IS NOT NULL
    ORDER BY server_id, created_at ASC
  ) AS keep
)
AND server_id IS NOT NULL;

-- ── 3. Add UNIQUE constraint on lessons.server_id ──────────────────────────
-- Partial index: only applies to non-null server_id values.
-- Postgres treats NULLs as distinct, so multiple rows with server_id = NULL
-- are still allowed (fine for brand-new records that haven't synced yet).
--
-- NOTE: This does NOT protect against the stale-INSERT bug (see header
-- comment for explanation). It is general data integrity: prevents manual
-- INSERTs or future code bugs that explicitly reuse a non-null server_id.
CREATE UNIQUE INDEX IF NOT EXISTS idx_lessons_server_id
  ON lessons (server_id)
  WHERE server_id IS NOT NULL;

-- ── 4. Add UNIQUE constraint on exams.server_id ────────────────────────────
CREATE UNIQUE INDEX IF NOT EXISTS idx_exams_server_id
  ON exams (server_id)
  WHERE server_id IS NOT NULL;
